function getMessage(dictionary, key) {
  return key.split('.').reduce((value, part) => (value ? value[part] : undefined), dictionary)
}

function loadLocale() {
  try {
    const saved = localStorage.getItem(LOCALE_KEY)
    if (saved === 'km' || saved === 'en') return saved
  } catch {
    // storage unavailable
  }
  return 'km'
}

export const locale = ref(loadLocale())
export const isKhmer = computed(() => locale.value === 'km')

export function t(key, params = {}) {
  const value = getMessage(messages[locale.value], key) ?? getMessage(messages.km, key) ?? key
  return Object.entries(params).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value,
  )
}

export function setLocale(next) {
  locale.value = next === 'en' ? 'en' : 'km'
  document.documentElement.lang = locale.value
  try {
    localStorage.setItem(LOCALE_KEY, locale.value)
  } catch {
    // storage unavailable
  }
  return locale.value
}

export function toggleLocale() {
  return setLocale(isKhmer.value ? 'en' : 'km')
}

export function formatNumber(value, pad = 0) {
  return isKhmer.value ? toKhmerNumber(value, pad) : String(value).padStart(pad, '0')
}

export function formatTime(value) {
  const [hours = '00', minutes = '00'] = String(value || '00:00').split(':')
  return `${formatNumber(hours, 2)}:${formatNumber(minutes, 2)}`
}

export function pickLocalized(km, en) {
  return isKhmer.value ? km : en || km
}

